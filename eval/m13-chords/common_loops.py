"""M13.16: write src/song/common-loops.ts — 3 verse and 3 chorus loops per gb-mcp genre and mode — from the loop counts
of loops_by_mode.py. The dataset (Chordonomicon, CC BY-NC 4.0) and the counts stay on this Mac; only the progressions
(Roman numerals) go into gb-mcp. Run from this folder, with the models venv:
    python loops_by_mode.py <chordonomicon_v2.csv at ailsntua/Chordonomicon@f3a8b67> bymode.json
    python common_loops.py bymode.json ../../src/song/genres.ts ../../src/song/common-loops.ts

A mode with fewer than MIN_SONGS songs uses the pooled loops of all genres. The template's own loops are skipped (the
variants add new ones); a variant's chorus loop differs from its verse loop; each loop starts where songs most often
start it (verses on the tonic, choruses by the counted openings).
"""
import json, re, sys
from stats import changes, loop_class

MIN_SONGS = 300
ALIAS = {"ambient trance (William Orbit style)": "ambient trance", "Levantine ethereal strings (Fairuz style)": "Levantine strings",
         "epic orchestral (Hans Zimmer style)": "epic orchestral", "classical/pop crossover": None}
NAME = re.compile(r'^  ("([^"]+)"|([a-z]+)): \{', re.M)
PROG = re.compile(r'progression: (POP_PROG|\{ minor: \{ a: "([^"]+)", b: "([^"]+)" \}, major: \{ a: "([^"]+)", b: "([^"]+)" \} \})')
NUM = re.compile(r"^(b|#)?(vii|iii|vi|iv|ii|v|i|VII|III|VI|IV|II|V|I)(ø|°)?")
TONIC = {"major": "I", "minor": "i"}


def triads(p: str) -> list[str]:
    out = []
    for tok in p.replace("|", " ").split():
        m = NUM.match(tok)
        out.append((m[1] or "") + m[2] + ("°" if m[3] else ""))
    return out


def classes(p: str) -> set[str]:
    c = changes(triads(p)); cyc = c + c[:3]
    return {loop_class(cyc[j:j + 4]) for j in range(len(c)) if len(set(cyc[j:j + 4])) == 4}


def rotations(cls: str) -> list[str]:
    w = cls.split()
    return [" ".join(w[i:] + w[:i]) for i in range(4)]


def start(cls: str, opens: dict, mode: str, tonic_first: bool) -> str:
    rots = rotations(cls)
    if not tonic_first:
        best = max(rots, key=lambda r: opens.get(r, 0))
        if opens.get(best, 0) > 0:
            return best
    return next(r for r in rots if r.split()[0] == TONIC[mode])


def main(bymode: str, genres_ts: str, out: str):
    st = json.load(open(bymode)); src = open(genres_ts).read()
    pop = re.search(r'const POP_PROG = \{ minor: \{ a: "([^"]+)", b: "([^"]+)" \}, major: \{ a: "([^"]+)", b: "([^"]+)" \} \}', src)
    names = [(m.start(), m[2] or m[3]) for m in NAME.finditer(src)]
    entries = []
    for i, (pos, name) in enumerate(names):
        end = names[i + 1][0] if i + 1 < len(names) else len(src)
        m = PROG.search(src, pos, end)
        if not m:
            continue
        prog = pop.groups() if m[1] == "POP_PROG" else m.groups()[1:]
        own = {"minor": classes(prog[0]) | classes(prog[1]), "major": classes(prog[2]) | classes(prog[3])}
        g = ALIAS.get(name, name)
        modes = {}
        for mode in ("major", "minor"):
            pooled = g is None or g not in st or st[g][mode]["songs"] < MIN_SONGS
            s = st["_all" if pooled else g][mode]
            verse = [c for c, _ in s["verse"] if c not in own[mode]][:3]
            chorus, used = [], set()
            for k in range(3):
                pick = next(c for c, _ in s["chorus"] if c not in own[mode] and c != verse[k] and c not in used)
                used.add(pick); chorus.append(pick)
            opens = dict(s["chorus_open"])
            fmt = lambda c, tonic_first: " | ".join(start(c, opens, mode, tonic_first).split())
            modes[mode] = {"verse": [fmt(c, True) for c in verse], "chorus": [fmt(c, False) for c in chorus], "pooled": pooled}
        entries.append((name, modes))
    lines = ['/**',
             ' * Common 4-chord loops per genre and mode (M13.16) for gb_song template {variant: 1–3}: the loops heard most often in',
             ' * the verses and choruses of songs tagged with the genre in Chordonomicon (Kantarelis et al. 2024, arXiv 2410.22046).',
             ' * The dataset is CC BY-NC 4.0 and is not part of gb-mcp; only these common progressions — general musical facts — are.',
             ' * Roman numerals, one chord per bar. pooled: too few songs carry the genre\'s tags (< 300 in that mode), so the loops',
             ' * of all genres together. Generated by eval/m13-chords/common_loops.py — do not edit by hand.',
             ' */',
             'export type CommonLoops = { verse: readonly string[]; chorus: readonly string[]; pooled: boolean };',
             'export const COMMON_LOOPS: Record<string, { major: CommonLoops; minor: CommonLoops }> = {']
    for name, modes in entries:
        lines.append(f"  {json.dumps(name)}: {{")
        for mode in ("major", "minor"):
            v = modes[mode]
            lines.append(f"    {mode}: {{ verse: {json.dumps(v['verse'])}, chorus: {json.dumps(v['chorus'])}, pooled: {str(v['pooled']).lower()} }},")
        lines.append("  },")
    lines.append("};")
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(*sys.argv[1:4])
